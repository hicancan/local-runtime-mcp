import { readFile, writeFile, mkdir } from 'node:fs/promises';

// package.json is the release version source for the host and its bundled bridge.
const root = new URL('../../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('browser-extension/package.json', root), 'utf8'));
if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(pkg.version)) throw new Error('invalid release version');
await mkdir(new URL('internal/version/', root), { recursive: true });
await writeFile(new URL('internal/version/version.go', root), `// Code generated by browser-extension/scripts/generate-version.mjs; DO NOT EDIT.\npackage version\n\nconst Version = ${JSON.stringify(pkg.version)}\n`);
await writeFile(new URL('browser-extension/src/version.ts', root), `// Generated from package.json; do not edit.\nexport const VERSION = ${JSON.stringify(pkg.version)};\n`);
const manifestPath = new URL('internal/browser/extension/manifest.json', root);
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.version = pkg.version;
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
